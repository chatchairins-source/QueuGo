const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const root=path.resolve(__dirname,'..');
const workflow=fs.readFileSync(path.join(root,'.github/workflows/build-native-rider-pilot.yml'),'utf8');
const start=workflow.indexOf('  parallel-role-smoke:\n');
const end=workflow.indexOf('\n  native-pilot:',start);
assert(start>=0 && end>start);
const job=workflow.slice(start,end);
assert(job.includes('node tests/native-parallel-rider-maven-recovery.cjs'),'guard runs in real role job');
assert(job.includes('max-parallel: 2') && job.includes('role: [customer, merchant, rider]'),'retain all roles with bounded parallel downloads');
assert(job.includes('python3 native-android/qa/gradle_maven_recovery.py'),'same fail-closed runner as Customer and map jobs');
assert(job.includes(':testDebugUnitTest') && job.includes(':assembleDebug'),'real units/APK tasks preserved');
assert(job.includes('artifacts/parallel-${role}/gradle-first-attempt.log'),'first failure is retained');
assert(job.includes('verify-16kb-page-size.py'),'actual APK integrity gate remains');
assert(!job.includes('--offline') && !job.includes('--continue'),'no bypass');
execFileSync('python3',['-m','unittest','discover','-s','native-android/qa','-p','test_gradle_maven_recovery.py'],{cwd:root,stdio:'inherit'});
console.log('Parallel native Maven contract + isolated CLI/HTTP regressions PASS; real Android acceptance still required');
