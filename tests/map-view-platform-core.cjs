const html=fs.readFileSync(path.resolve(__dirname,"../map-view/index.html"),"utf8");
let checks=0;
const ok=(v,m)=>{assert.ok(v,m);checks++};
const has=(x,m)=>ok(html.includes(x),m||("missing "+x));
