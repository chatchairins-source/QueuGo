ok(scripts.length===1,"Map View must keep one inline application script");
new Function(scripts[0]);checks++;

has("QueueGo Map","QueueGo Map branding required");
has('id="placeSearchForm"',"place search UI required");
has("engineGeocode","forward geocoding required");
has("engineReverse","reverse geocoding required");
has("engineNearestRoad","nearest road calculation required");
has("greatCircleMeters","distance calculation required");
has("bearingDegrees","bearing calculation required");
has("engineRoute","multi-coordinate routing required");
has("engineMatrix","route matrix required");
has("engineOptimizeStops","waypoint optimization required");
has("engineMatchTrace","GPS trace map matching required");
has("engineNearby","nearby place search required");
has("QueueGoMapEngine","public QueueGo Map calculation surface required");
has('data-tool="inspect"',"coordinate inspection tool required");
has('data-tool="measure"',"multi-point distance tool required");
has('data-tool="multistop"',"multi-stop routing tool required");
has('data-tool="nearby"',"nearby tool required");
has("สูงสุด 12 จุด","multi-stop visible limit required");
has("/table/v1/driving/","OSRM table service required");
has("/trip/v1/driving/","OSRM trip optimization required");
has("/match/v1/driving/","OSRM match service required");
has("/nearest/v1/driving/","OSRM nearest service required");
has('id="matrixWrap"',"matrix output required");
has('id="copyInspectCoords"',"coordinate copy control required");
has('class="qg-wordmark">QueueGo Map',"visible QueueGo Map wordmark required");
has("viewbox=102.4,15.8,103.5,14.1","Buriram-biased search required");
ok(!html.includes("countrycodes=th"),"search must not be hard-limited to Thailand");
ok(!html.includes("maps.googleapis.com"),"must not depend on Google map data");

