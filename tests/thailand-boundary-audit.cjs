'use strict';
const assert=require('node:assert/strict');
const {PIN,SAMPLES,validateGeometry,covers,parsePinnedBoundary,liveAuditSql}=require('../scripts/audit-thailand-boundary.cjs');
const outer=[[99,9],[101,9],[101,11],[99,11],[99,9]];
const hole=[[99.5,9.5],[100.5,9.5],[100.5,10.5],[99.5,10.5],[99.5,9.5]];
const polygons=validateGeometry({type:'Polygon',coordinates:[outer,hole]});
assert.equal(covers(polygons,9.25,99.25),true);
assert.equal(covers(polygons,10,100),false,'hole interior must not count as land');
assert.equal(covers(polygons,9,100),true,'outer boundary covered');
assert.equal(covers(polygons,9.5,100),true,'hole boundary covered');
assert.equal(covers(polygons,12,100),false);
assert.equal(covers(polygons,NaN,100),false);
const island=[[102,12],[103,12],[103,13],[102,13],[102,12]];
const multi=validateGeometry({type:'MultiPolygon',coordinates:[[outer,hole],[island]]});
assert.equal(covers(multi,12.5,102.5),true,'disconnected islands retained');
assert.equal(covers(multi,11.5,101.5),false,'sea between polygons excluded');
assert.throws(()=>validateGeometry({type:'Polygon',coordinates:[[...outer.slice(0,-1)]]}),/unclosed/);
assert.throws(()=>validateGeometry({type:'Polygon',coordinates:[[[99,9],[999,9],[100,10],[99,9]]]}),/coordinate/);
assert.throws(()=>validateGeometry({type:'Polygon',coordinates:[]}),/empty/);
assert.throws(()=>parsePinnedBoundary(Buffer.from('version https://git-lfs.github.com/spec/v1')),/checksum/);
assert.throws(()=>parsePinnedBoundary(Buffer.from('{}')),/checksum/);
assert.equal(PIN.license,'ODbL-1.0','do not mislabel this OSM-derived boundary CC-BY');
assert.equal(SAMPLES.length,22);
const sql=liveAuditSql();
assert.match(sql,/queuego_service_area_route_status/);
assert.doesNotMatch(sql,/\b(insert|update|delete|create|alter|drop|truncate)\b/i);
assert.equal((sql.match(/\('\w/g)||[]).length,22);
console.log(JSON.stringify({checks:18,failures:0,scope:'offline boundary audit: holes, edges, islands, pinned payload, honest license and read-only live SQL; no Production changes'}));
