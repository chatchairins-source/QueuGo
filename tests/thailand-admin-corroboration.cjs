'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const file=path.join(__dirname,'..','data','maps','thailand-admin-corroboration-review.json');
const r=JSON.parse(fs.readFileSync(file,'utf8'));
assert.equal(r.execution,'review_only_no_database_write');
assert.equal(r.production_import_allowed,false);
assert.equal(r.canonical_resolution,'unresolved');
assert.equal(r.conflict.canonical_code_candidate,null);
assert.equal(r.conflict.canonical_code_approved,false);
assert.deepEqual([r.conflict.oad_candidate,r.conflict.hdx_candidate],['4026','4029']);
assert.ok(Array.isArray(r.evidence_sources)&&r.evidence_sources.length>=4);
assert.ok(r.evidence_sources.every(s=>s.canonical_eligible===false));
const bora=r.evidence_sources.filter(s=>s.publisher.includes('Bureau of Registration Administration'));
assert.ok(bora.length>=2);
assert.ok(bora.every(s=>s.observed_rows?.some(x=>x.code==='4029'&&x.name.includes('เวียงเก่า'))));
assert.ok(bora.every(s=>s.checksum_status!=='verified'));
assert.ok(bora.every(s=>s.freshness_status!=='current_verified'));
assert.equal(r.gates.identity_code_correctness,'blocked');
assert.equal(r.gates.current_primary_reference,'blocked');
assert.equal(r.gates.postgis_release_acceptance,'not_tested');
const doae=r.evidence_sources.filter(s=>s.publisher==='Department of Agricultural Extension');
assert.ok(doae.length>=2);
assert.ok(doae.every(s=>s.canonical_eligible===false&&s.primary_dopa_bytes===false));
const current=doae.find(s=>s.observed_data_date==='2026-10-26');
assert.ok(current);
assert.deepEqual(current.observed_rows.map(x=>x.code),['402900','402901','402902','402903']);
assert.ok(current.observed_rows.slice(1).every(x=>x.parent_code==='4029'));
assert.equal(r.gates.current_government_operational_corroboration,'supports_4029_hierarchy');
assert.equal(r.gates.identity_code_correctness,'blocked');
console.log(JSON.stringify({checks:21,failures:0,scope:'current government corroboration may support 4029 hierarchy but cannot approve canonical identity or Production'}));
