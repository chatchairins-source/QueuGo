-- A simple future/crash-safe fixture. No app session, no real finances.
CREATE OR REPLACE FUNCTION public.qg_test_seed_timeout(p_id uuid, p_minutes integer)
RETURNS void LANGUAGE plpgsql AS $fixture$
BEGIN
 INSERT INTO public.orders(id,status,rider_id,rider_assigned_at,market_order_id,paid_at,total_amount,
    created_at,rider_search_started_at,order_type,sales_channel)
 VALUES(p_id,'searching_rider',NULL,NULL,NULL,NULL,100,now()-interval '45 minutes',
    now()-make_interval(mins=>p_minutes),'shopping','QUEUEGO_DELIVERY');
 INSERT INTO public.payments(order_id,status,payment_method,paid_at,transaction_reference,amount)
 VALUES(p_id,'pending','cash',NULL,NULL,100);
 INSERT INTO public.deliveries(order_id,status) VALUES(p_id,'pending');
 INSERT INTO public.queuego_cash_order_locks(order_id) VALUES(p_id);
END $fixture$;
SELECT public.qg_test_seed_timeout('00000000-0000-4000-8000-000000001001',31);
INSERT INTO public.qg_rider_order_offers VALUES(
'00000000-0000-4000-8000-000000001001','00000000-0000-4000-8000-000000001002',
now()-interval '1 minute',now()+interval '1 minute',1);
DO $check$
DECLARE n int; oid uuid:='00000000-0000-4000-8000-000000001001';
BEGIN
 n:=qg_private.cancel_rider_timeout_cash(20);
 IF n<>1 THEN RAISE EXCEPTION '30 minute expired order must be cancelled exactly once: %',n; END IF;
 IF (SELECT status FROM public.orders WHERE id=oid)<>'cancelled'
 OR (SELECT status FROM public.payments WHERE order_id=oid)<>'cancelled'
 OR (SELECT status FROM public.deliveries WHERE order_id=oid)<>'cancelled'
 THEN RAISE EXCEPTION 'order/payment/delivery must all atomically cancel'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.queuego_cash_order_locks WHERE order_id=oid)
 THEN RAISE EXCEPTION 'cash marker must be retained'; END IF;
 IF EXISTS(SELECT 1 FROM public.qg_rider_order_offers WHERE order_id=oid)
 THEN RAISE EXCEPTION 'live offer must be withdrawn'; END IF;
 IF (SELECT count(*) FROM public.qg_rider_offer_history WHERE order_id=oid)<>1
 THEN RAISE EXCEPTION 'offer history must be preserved'; END IF;
 IF (SELECT count(*) FROM public.audit_logs WHERE entity_id=oid AND action='no_rider_timeout')<>1
 THEN RAISE EXCEPTION 'timeout transition must be audited exactly once'; END IF;
 IF (SELECT count(*) FROM public.notifications WHERE reference_id=oid)<>2
 THEN RAISE EXCEPTION 'customer and shop must get exactly one notification each'; END IF;
 IF qg_private.cancel_rider_timeout_cash(20)<>0
 THEN RAISE EXCEPTION 'repeat scheduler must be idempotent'; END IF;
END $check$;
