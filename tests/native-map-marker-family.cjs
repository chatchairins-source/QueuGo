assert(pickup !== drop && rider !== pickup && rider !== drop);
for (const svg of [pickup, drop, rider]) {
  assert(svg.includes('#FFFFFFFF') && svg.includes('#220D2338'));
  assert(!svg.includes('<text'));
}
