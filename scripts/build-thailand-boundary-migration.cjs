#!/usr/bin/env node
'use strict';
// Regenerate only from the checksum-pinned, unmodified source component.
const fs=require('node:fs');
const crypto=require('node:crypto');
const {PIN,parsePinnedBoundary}=require('./audit-thailand-boundary.cjs');

const ACCEPTANCE=[
  ['Ranong',9.9529,98.6085,true],['Ko Tao',10.0956,99.8400,true],
  ['Phi Phi Don',7.7407,98.7784,true],['Lipe',6.4877,99.3010,true],
  ['Ko Lanta clinic reference',7.598579,99.036197,true],
  ['Bangkok',13.7563,100.5018,true],['Chiang Mai',18.7883,98.9853,true],
  ['Buriram',14.9929,103.1080,true],['Kuala Lumpur',3.1390,101.6869,false],
  ['Phnom Penh',11.5564,104.9282,false],['Pakse',15.1200,105.8000,false],
  ['Langkawi',6.3500,99.8000,false],['Gulf open water',10.0000,100.5000,false],
  ['Andaman open water',9.0000,95.0000,false]
];
const literal=s=>"'"+String(s).replace(/'/g,"''")+"'";
const values=()=>ACCEPTANCE.map(([name,lat,lng,expected])=>`(${literal(name)},${lat},${lng},${expected})`).join(',\n');

function renderMigration(buffer){
  parsePinnedBoundary(buffer);
  const geometry=JSON.stringify(JSON.parse(buffer.toString('utf8')).features[0].geometry);
  const geometrySha=crypto.createHash('sha256').update(geometry).digest('hex');
  return `-- Generated by scripts/build-thailand-boundary-migration.cjs from exact pinned bytes.
-- Separate unmodified geoBoundaries / OpenStreetMap / Wambacher ODbL-1.0 boundary component.
-- Original download: ${PIN.url}
-- Original SHA-256: ${PIN.sha256}; bytes: ${PIN.bytes}; represented year: ${PIN.represented_year}.
-- Attribution: ${PIN.attribution}. License: https://opendatacommons.org/licenses/odbl/1-0/
-- Source redistribution and exact download links: docs/map-data.html.
-- No Places records, private data, prices, orders, route caps or deny rules are modified.
do $boundary_release$
declare
 v_geojson text := ${literal(geometry)};
 v_geom extensions.geometry;
 v_old public.queuego_order_service_area_rules%rowtype;
 v_existing public.queuego_order_service_area_rules%rowtype;
 v_new_id uuid;
 v_source_ref text := 'THA-ADM0-76911100@sha256:${PIN.sha256}';
begin
 lock table public.queuego_order_service_area_rules in share row exclusive mode;
 select * into v_existing from public.queuego_order_service_area_rules
 where country_code='TH' and lower(name)='thailand nationwide launch' and revision=2;
 if found then
  if v_existing.source_ref<>v_source_ref or v_existing.source_license<>'ODbL-1.0' then
   raise exception 'BOUNDARY_REVISION_CONFLICT';
  end if;
  return; -- Never resurrect a rule intentionally deactivated after this release.
 end if;
 select * into strict v_old from public.queuego_order_service_area_rules
 where country_code='TH' and lower(name)='thailand nationwide launch' and active
 and revision=1 and mode='allow' and source='natural_earth';
 if exists(select 1 from public.queuego_order_service_area_rules where country_code='TH'
  and lower(name)='thailand nationwide launch' and revision>1) then
  raise exception 'BOUNDARY_SUCCESSOR_EXISTS';
 end if;
 if encode(extensions.digest(v_geojson,'sha256'),'hex')<>${literal(geometrySha)} then
  raise exception 'BOUNDARY_PAYLOAD_MISMATCH';
 end if;
 v_geom:=extensions.st_setsrid(extensions.st_geomfromgeojson(v_geojson),4326);
 if not extensions.st_isvalid(v_geom) or extensions.st_isempty(v_geom)
 or extensions.geometrytype(v_geom)<>'MULTIPOLYGON'
 or extensions.st_numgeometries(v_geom)<>70 or extensions.st_npoints(v_geom)<>93940
 or extensions.st_area(v_geom::extensions.geography) not between 450000000000 and 600000000000 then
  raise exception 'INVALID_THAILAND_BOUNDARY';
 end if;
 if exists(
  select 1 from (values ${values()}) as c(name,lat,lng,expected)
  where extensions.st_covers(v_geom,extensions.st_setsrid(extensions.st_makepoint(c.lng,c.lat),4326))<>c.expected
  or extensions.st_covers(v_geom,extensions.st_setsrid(extensions.st_makepoint(c.lng,c.lat+0.001),4326))<>c.expected
 ) then raise exception 'THAILAND_BOUNDARY_ACCEPTANCE_FAILED'; end if;

 insert into public.queuego_place_sources(source_key,source_name,license_id,license_url,
  attribution_requirement,update_policy,allowed_storage,allowed_redistribution,metadata)
 values('geoboundaries_th_adm0','geoBoundaries Thailand ADM0 / OpenStreetMap / Wambacher','ODbL-1.0',
  'https://opendatacommons.org/licenses/odbl/1-0/',${literal(PIN.attribution)},
  'Pinned unmodified component; review exact payload, license, coast/island and foreign/sea fixtures before a new rule revision.',
  true,true,jsonb_build_object('boundary_id',${literal(PIN.boundary_id)},'download_url',${literal(PIN.url)},
   'sha256',${literal(PIN.sha256)},'geometry_sha256',${literal(geometrySha)},'bytes',${PIN.bytes},
   'represented_year',${literal(PIN.represented_year)},'distribution','unmodified separate component',
   'attribution_url','docs/map-data.html'))
 on conflict(source_key) do update set source_name=excluded.source_name,license_id=excluded.license_id,
  license_url=excluded.license_url,attribution_requirement=excluded.attribution_requirement,
  update_policy=excluded.update_policy,allowed_storage=excluded.allowed_storage,
  allowed_redistribution=excluded.allowed_redistribution,metadata=excluded.metadata,updated_at=now();

 insert into public.queuego_order_service_area_rules(name,country_code,verticals,mode,
  admin_place_id,custom_boundary,specificity,max_direct_delivery_km,active,effective_from,
  revision,source,source_ref,source_license,metadata)
 values(v_old.name,v_old.country_code,v_old.verticals,v_old.mode,null,v_geom::extensions.geography,
  v_old.specificity,v_old.max_direct_delivery_km,true,now(),2,'geoboundaries_th_adm0',v_source_ref,'ODbL-1.0',
  v_old.metadata || jsonb_build_object('supersedes_rule_id',v_old.rule_id,'supersedes_revision',v_old.revision,
   'boundary_id',${literal(PIN.boundary_id)},'source_sha256',${literal(PIN.sha256)},
   'geometry_sha256',${literal(geometrySha)},'represented_year',${literal(PIN.represented_year)},
   'attribution',${literal(PIN.attribution)},'attribution_url','docs/map-data.html',
   'reason','Detailed land boundary for coastal/island service coverage; no buffers or country bounding-box shortcut'))
 returning rule_id into v_new_id;
 update public.queuego_order_service_area_rules set active=false,effective_to=now(),updated_at=now()
 where rule_id=v_old.rule_id;
 insert into public.audit_logs(action,entity_type,entity_id,description,metadata)
 values('service_area_rule_revised','queuego_order_service_area_rules',v_new_id,
  'Replace coarse nationwide land boundary with pinned detailed boundary; preserve prior rule and source.',
  jsonb_build_object('previous_rule_id',v_old.rule_id,'previous_revision',v_old.revision,'revision',2,
   'source_ref',v_source_ref,'source_license','ODbL-1.0','max_direct_delivery_km',v_old.max_direct_delivery_km,
   'verticals',to_jsonb(v_old.verticals),'specificity',v_old.specificity,'release','detailed_thailand_service_boundary'));
end;
$boundary_release$;
`;
}
if(require.main===module){
 try{
  if(!process.argv[2]||!process.argv[3])throw Error('Usage: node scripts/build-thailand-boundary-migration.cjs <pinned.geojson> <CLI-created.sql>');
  if(!fs.existsSync(process.argv[3]))throw Error('Create migration using Supabase CLI first');
  const rendered=renderMigration(fs.readFileSync(process.argv[2]));
  const existing=fs.readFileSync(process.argv[3],'utf8');
  if(existing.trim()&&existing!==rendered)throw Error('Refusing to overwrite a different migration');
  fs.writeFileSync(process.argv[3],rendered);
  console.log(JSON.stringify({migration:process.argv[3],source_sha256:PIN.sha256,bytes:Buffer.byteLength(rendered)}));
 }catch(error){console.error(error.message);process.exitCode=1;}
}
module.exports={ACCEPTANCE,renderMigration};
